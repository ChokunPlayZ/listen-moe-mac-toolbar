import RadioCore
import SwiftUI

struct FuriganaText: View {
    let text: String
    let readingSize: CGFloat
    private let segments: [FuriganaSegment]
    @Environment(\.lineLimit) private var lineLimit

    init(_ text: String, enabled: Bool, readingSize: CGFloat = 7) {
        self.text = text
        self.readingSize = readingSize
        segments = enabled ? Furigana.segments(for: text) : []
    }

    var body: some View {
        if segments.contains(where: { $0.reading != nil }) {
            RubyLayout(lineLimit: lineLimit) {
                ForEach(segments.indices, id: \.self) { index in
                    ruby(text: segments[index].text, reading: segments[index].reading)
                }
                ruby(text: "…", reading: nil)
            }
            .clipped()
            .accessibilityElement(children: .ignore)
            .accessibilityLabel(text)
            .help("Furigana is generated by macOS. Proper-name readings may differ.")
        } else {
            Text(text)
        }
    }

    private func ruby(text: String, reading: String?) -> some View {
        VStack(spacing: 0) {
            Text(reading ?? "")
                .font(.system(size: readingSize))
                .foregroundStyle(.secondary)
                .lineLimit(1)
                .frame(height: readingSize + 2)
            Text(text).lineLimit(1)
        }
        // Parent rows align icons with the main text, not the reading above it.
        .alignmentGuide(.firstTextBaseline) { $0[.lastTextBaseline] }
    }
}

private struct RubyLayout: Layout {
    let lineLimit: Int?
    private let lineSpacing: CGFloat = 2

    func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
        arrange(width: proposal.width, subviews: subviews).size
    }

    func placeSubviews(in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) {
        let layout = arrange(width: bounds.width, subviews: subviews)
        for index in subviews.indices {
            if let frame = layout.frames[index] {
                subviews[index].place(
                    at: CGPoint(x: bounds.minX + frame.minX, y: bounds.minY + frame.minY),
                    anchor: .topLeading, proposal: ProposedViewSize(frame.size)
                )
            } else {
                // Hidden overflow and the unused ellipsis are clipped outside the label.
                subviews[index].place(at: CGPoint(x: bounds.maxX + 10_000, y: bounds.minY), anchor: .topLeading, proposal: .zero)
            }
        }
    }

    func explicitAlignment(
        of guide: VerticalAlignment, in bounds: CGRect, proposal: ProposedViewSize,
        subviews: Subviews, cache: inout ()
    ) -> CGFloat? {
        guard guide == .firstTextBaseline || guide == .lastTextBaseline else { return nil }
        let layout = arrange(width: bounds.width, subviews: subviews)
        let visible = subviews.indices.filter { layout.frames[$0] != nil }
        guard let index = guide == .firstTextBaseline ? visible.first : visible.last,
              let frame = layout.frames[index] else { return nil }
        let dimensions = subviews[index].dimensions(in: ProposedViewSize(frame.size))
        return frame.minY + dimensions[guide]
    }

    private func arrange(width: CGFloat?, subviews: Subviews) -> (size: CGSize, frames: [CGRect?]) {
        let sizes = subviews.map { $0.sizeThatFits(.unspecified) }
        guard let ellipsis = sizes.last else { return (.zero, []) }
        let naturalWidth = sizes.dropLast().reduce(0) { $0 + $1.width }
        let available = max(0, width.flatMap { $0.isFinite ? $0 : nil } ?? naturalWidth)
        let rowHeight = sizes.map(\.height).max() ?? 0
        let rowStride = rowHeight + lineSpacing
        let maximumLines = max(1, lineLimit ?? Int.max)
        var frames = [CGRect?](repeating: nil, count: sizes.count)
        var x: CGFloat = 0
        var line = 0
        var truncated = false

        for index in sizes.dropLast().indices {
            let itemWidth = min(sizes[index].width, available)
            if x > 0, x + itemWidth > available {
                line += 1
                x = 0
            }
            guard line < maximumLines else { truncated = true; break }
            frames[index] = CGRect(x: x, y: CGFloat(line) * rowStride, width: itemWidth, height: rowHeight)
            x += itemWidth
        }

        if truncated {
            let lastRowY = CGFloat(maximumLines - 1) * rowStride
            let ellipsisWidth = min(ellipsis.width, available)
            var lastRow = frames.indices.filter { frames[$0]?.minY == lastRowY }
            while let last = lastRow.last, let frame = frames[last], frame.maxX + ellipsisWidth > available {
                frames[last] = nil
                lastRow.removeLast()
            }
            let endX = lastRow.last.flatMap { frames[$0]?.maxX } ?? 0
            frames[frames.count - 1] = CGRect(x: endX, y: lastRowY, width: ellipsisWidth, height: rowHeight)
        }
        let visible = frames.compactMap { $0 }
        return (
            CGSize(width: visible.map(\.maxX).max() ?? 0, height: visible.map(\.maxY).max() ?? 0), frames
        )
    }
}
